// FS v9 Results summaries served by the Backend.
//
// The Experiment detail and the Results snapshot render the generated summary
// of `experiment-results-summary` (`.memon/index/results/<experiment-id>.json`).
// Its freshness follows the input fingerprints:
//
// - the description file `experiment.json` is fingerprinted on every request
//   (the Experiment bundle read of the same request also reads it);
// - member README and `result.csv` fingerprints come from the summary index,
//   reused within the member windows that already govern the Experiment
//   detail's member facts (central) or re-taken (strict policy, an explicit
//   refresh, the snapshot route);
// - a stored summary is served only when it was generated by this release
//   for exactly these inputs; otherwise it is regenerated (concurrent requests
//   share one regeneration) and stored best effort.
//
// A member path that escapes the Project is never read: its inputs count as
// absent.

