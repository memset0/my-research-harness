/** Re-take (0) or reuse member fingerprints within the detail's member window. */
export type MemberWindow = number | ((summary: RunSummary | null) => number)

export interface ExperimentResultsSummaryOptions {
  memberWindow: MemberWindow
  /** Generator role recorded in a regenerated summary. */
  role: IndexRole
  /** Declared-Run summaries shared with the request's other member reads. */
  lookup?: DeclaredRunLookup
}

/** A declared Run's summary (null when absent; throws for an escaping path). */
export type DeclaredRunLookup = (run: string) => Promise<RunSummary | null>

/**
 * Declared-Run summaries through the summary index, memoized for one request
 * so the roster's deprecation flags and the Results inputs take each member
 * fingerprint once.
 */
export function declaredRunLookup(project: ProjectConfig, window: MemberWindow): DeclaredRunLookup {
  const memo = new Map<string, Promise<RunSummary | null>>()
  return (run) => {
    let pending = memo.get(run)
    if (!pending) {
      pending = indexedDeclaredRun(project, run, window)
      memo.set(run, pending)
    }
    return pending
  }
}

export interface ExperimentResultsSummary {
  summary: ResultsSummary
  /** `RESULTS_CACHE_FAILED` when a regenerated summary could not be stored. */
  warnings: ResultsDiagnostic[]
  /** `hit`: a stored summary was fresh; `regenerated`: computed from the inputs. */
  cache: 'hit' | 'regenerated'
}

/** A failed Results snapshot: the status and body every mode answers with. */
export class BackendResultsError extends Error {
  constructor(
    public readonly status: 400 | 404 | 422,
    public readonly body: ReturnType<typeof toBackendResultsErrorResponse>,
  ) {
    super(body.error.message)
    this.name = 'BackendResultsError'
  }
}

export function backendResultsError(
  status: 400 | 404 | 422,
  error: BackendResultsSummaryError,
  updatedAt: string | null,
): BackendResultsError {
  return new BackendResultsError(status, toBackendResultsErrorResponse(error, updatedAt))
}

const EXPERIMENTS_RELDIR = 'docs/experiments'

/** The summary input set of a parsed Experiment bundle (null for a legacy single file). */
export function resultsInputSet(experiment: Experiment): ResultsSummaryInputSet | null {
  if (!EXPERIMENT_DIR_REGEX.test(experiment.id) || !experiment.path.endsWith('README.md')) {
    return null
  }
  const experimentDir = `${EXPERIMENTS_RELDIR}/${experiment.id}`
  const readmeRuns = [...experiment.frontMatter.runs]
  const members = [...new Set(readmeRuns.filter((run) => isRunPath(run)))]
  const descriptionKey = `${experimentDir}/${EXPERIMENT_DESCRIPTION_FILE}`
  return {
    experimentId: experiment.id,
    experimentDir,
    readmeRuns,
    members,
    descriptionKey,
    legacyResultsYaml: experiment.documents?.results.exists === true,
    keys: [
      descriptionKey,
      ...members.flatMap((run) => [`${run}/README.md`, `${run}/${RESULT_FILE_NAME}`]),
    ],
  }
}

/**
 * A persisted fingerprint from a summary-index stat fingerprint
 * (`f:<dev>:<ino>:<size>:<mtime>:<ctime>`, optionally `readme:`-prefixed and
 * device-less); undefined when it is not a file fingerprint.
 */
export function persistedFromStatFingerprint(
  fingerprint: string,
): PersistedFingerprint | undefined {
  const parts = fingerprint.replace(/^readme:/, '').split(':')
  if (parts.length !== 6 || parts[0] !== 'f') return undefined
  const [ino, size, mtime, ctime] = parts.slice(2).map(Number)
  if (![ino, size, mtime, ctime].every((value) => Number.isFinite(value))) return undefined
  return { ino: ino!, size: size!, mtime_ms: mtime!, ctime_ms: ctime! }
}

/** The summary-index key of a Run's result file. */
export function runResultKey(dir: string): string {
  return `result:${join(dir, RESULT_FILE_NAME)}`
}

/**
 * The fingerprint of `<dir>/result.csv` through the summary index (null when
 * absent), reused within `maxAgeMs` of its last validation.
 */
export async function indexedRunResultFingerprint(
  project: ProjectConfig,
  dir: string,
  maxAgeMs: number,
): Promise<string | null> {
  const index = projectReadIndex(project.root)
  const path = join(dir, RESULT_FILE_NAME)
  await index.observe<true, Stats>(
    runResultKey(dir),
    maxAgeMs,
    () => statObservation(path),
    async () => true,
  )
  return index.peek(runResultKey(dir))?.fingerprint ?? null
}

function windowFor(window: MemberWindow, summary: RunSummary | null): number {
  return typeof window === 'function' ? window(summary) : window
}

/**
 * Member README and result fingerprints from the summary index. A member
 * whose path escapes the Project, or whose fingerprint cannot be taken, is
 * recorded as absent so the generator never reads it.
 */
async function memberFingerprints(
  project: ProjectConfig,
  members: readonly string[],
  window: MemberWindow,
  lookup: DeclaredRunLookup,
): Promise<Map<string, PersistedFingerprint | null>> {
  const known = new Map<string, PersistedFingerprint | null>()
  const index = projectReadIndex(project.root)
  await mapLimited(members, 16, async (run) => {
    const dir = join(project.root, ...run.split('/'))
    const readmeKey = `${run}/README.md`
    const resultKey = `${run}/${RESULT_FILE_NAME}`
    let summary: RunSummary | null
    try {
      summary = await lookup(run)
    } catch {
      known.set(readmeKey, null)
      known.set(resultKey, null)
      return
    }
    if (summary === null) {
      known.set(readmeKey, null)
      known.set(resultKey, null)
      return
    }
    const runFingerprint = index.peek(runSummaryKey(dir))?.fingerprint ?? null
    if (runFingerprint === null || runFingerprint.startsWith('dir:')) known.set(readmeKey, null)
    else {
      const readme = persistedFromStatFingerprint(runFingerprint)
      if (readme) known.set(readmeKey, readme)
    }
    try {
      const result = await indexedRunResultFingerprint(project, dir, windowFor(window, summary))
      if (result === null) known.set(resultKey, null)
      else {
        const persisted = persistedFromStatFingerprint(result)
        if (persisted) known.set(resultKey, persisted)
      }
    } catch {
      // Left unknown: the generator takes this fingerprint itself.
    }
  })
  return known
}

/** The stored summary of `experimentId` when it parses and its digest matches, read once per fingerprint. */
async function storedSummary(
  project: ProjectConfig,
  experimentId: string,
): Promise<ResultsSummary | null> {
  try {
    return await projectReadIndex(project.root).file(
      resultsSummaryPath(project.root, experimentId),
      `results-summary:${experimentId}`,
      0,
      (content) => verifiedSummary(content, experimentId),
    )
  } catch {
    return null
  }
}

function verifiedSummary(content: string, experimentId: string): ResultsSummary | null {
  let parsed: unknown
  try {
    parsed = JSON.parse(content)
  } catch {
    return null
  }
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) return null
  const summary = parsed as ResultsSummary
  if (summary.experiment !== experimentId) return null
  if (typeof summary.digest !== 'string') return null
  return resultsSummaryDigest(summary) === summary.digest ? summary : null
}

const regenerations = new Map<string, Promise<ExperimentResultsSummary>>()

function inputsDigest(inputs: Readonly<Record<string, PersistedFingerprint | null>>): string {
  return JSON.stringify(
    Object.entries(inputs).map(([key, value]) =>
      value ? [key, value.ino, value.size, value.mtime_ms, value.ctime_ms] : [key],
    ),
  )
}

async function regenerate(
  project: ProjectConfig,
  set: ResultsSummaryInputSet,
  inputs: Record<string, PersistedFingerprint | null>,
  role: IndexRole,
): Promise<ExperimentResultsSummary> {
  const key = `${project.root}\0${set.experimentId}\0${inputsDigest(inputs)}`
  const pending = regenerations.get(key)
  if (pending) return pending
  const run = (async (): Promise<ExperimentResultsSummary> => {
    const summary = await generateResultsSummaryFromDisk(project.root, set, inputs, { role })
    if (project.readOnly === true) return { summary, warnings: [], cache: 'regenerated' }
    try {
      await writeResultsSummary(project.root, summary)
      return { summary, warnings: [], cache: 'regenerated' }
    } catch (error) {
      return {
        summary,
        cache: 'regenerated',
        warnings: [
          resultsDiagnostic(
            RESULTS_CACHE_FAILED,
            'warning',
            `.memon/index/results/${set.experimentId}.json`,
            `the regenerated Results summary was not stored: ${(error as Error)?.message ?? String(error)}`,
          ),
        ],
      }
    }
  })().finally(() => {
    regenerations.delete(key)
  })
  regenerations.set(key, run)
  return run
}

/** The RESULTS_NOT_FOUND summary of an Experiment without a bundle folder. */
function bundleLessSummary(experiment: Experiment, role: IndexRole): ResultsSummary {
  const experimentDir = `${EXPERIMENTS_RELDIR}/${experiment.id}`
  return generateResultsSummary({
    experimentId: experiment.id,
    experimentDir,
    description: missingExperimentDescription(`${experimentDir}/${EXPERIMENT_DESCRIPTION_FILE}`),
    legacyResultsYaml: false,
    members: [],
    inputs: {},
    newestInputMtime: null,
    generatedAt: formatIsoLocal(new Date()),
    generator: { release: MEMON_RELEASE, role },
  })
}

/** The failed summary of a missing or invalid description file. */
async function descriptionFailure(
  project: ProjectConfig,
  set: ResultsSummaryInputSet,
  experiment: Experiment,
  role: IndexRole,
): Promise<ResultsSummary> {
  const inputs = await takeResultsInputFingerprints(project.root, [set.descriptionKey])
  const fingerprint = inputs[set.descriptionKey]
  return generateResultsSummary({
    experimentId: set.experimentId,
    experimentDir: set.experimentDir,
    description:
      experiment.documents?.description ?? missingExperimentDescription(set.descriptionKey),
    legacyResultsYaml: set.legacyResultsYaml,
    members: [],
    inputs,
    newestInputMtime: fingerprint ? formatIsoLocal(new Date(fingerprint.mtime_ms)) : null,
    generatedAt: formatIsoLocal(new Date()),
    generator: { release: MEMON_RELEASE, role },
  })
}

/**
 * The current Results summary of a parsed Experiment bundle: the stored one
 * when it is fresh for the current inputs, otherwise regenerated. A failed
 * summary is a normal result (`outcome: 'failed'`), never an exception.
 */
export async function experimentResultsSummary(
  project: ProjectConfig,
  experiment: Experiment,
  options: ExperimentResultsSummaryOptions,
): Promise<ExperimentResultsSummary> {
  const set = resultsInputSet(experiment)
  if (!set)
    return { summary: bundleLessSummary(experiment, options.role), warnings: [], cache: 'hit' }
  const description = experiment.documents?.description
  if (!description?.exists || description.data === null) {
    // RESULTS_NOT_FOUND / INVALID_RESULTS do not depend on any member: no
    // member input is fingerprinted and nothing is stored.
    return {
      summary: await descriptionFailure(project, set, experiment, options.role),
      warnings: [],
      cache: 'hit',
    }
  }
  const lookup = options.lookup ?? declaredRunLookup(project, options.memberWindow)
  const known = await withAutomaticProjectFileContext(() =>
    memberFingerprints(project, set.members, options.memberWindow, lookup),
  )
  const inputs = await takeResultsInputFingerprints(project.root, set.keys, {
    known: (key) => known.get(key),
  })
  const stored = await storedSummary(project, set.experimentId)
  if (stored && isResultsSummaryFresh(stored, inputs, MEMON_RELEASE)) {
    return { summary: stored, warnings: [], cache: 'hit' }
  }
  return regenerate(project, set, inputs, options.role)
}

/**
 * Regenerate the stale summary of one Experiment from fingerprints the caller
 * already holds (the background validator's derived-index view). Returns
 * whether a summary was regenerated.
 */
export async function refreshStoredResultsSummary(
  project: ProjectConfig,
  set: ResultsSummaryInputSet,
  known: (key: string) => PersistedFingerprint | null | undefined,
  role: IndexRole,
): Promise<boolean> {
  const inputs = await takeResultsInputFingerprints(project.root, set.keys, { known })
  const stored = await storedSummary(project, set.experimentId)
  if (stored && isResultsSummaryFresh(stored, inputs, MEMON_RELEASE)) return false
  await regenerate(project, set, inputs, role)
  return true
}

/** The ISO8601 time a summary reports as its inputs' newest modification. */
export function summaryUpdatedAt(summary: ResultsSummary): string | null {
  return summary.newest_input_mtime ?? null
}

async function mapLimited<T>(
  items: readonly T[],
  limit: number,
  fn: (item: T) => Promise<void>,
): Promise<void> {
  let next = 0
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) await fn(items[next++]!)
    }),
  )
}
